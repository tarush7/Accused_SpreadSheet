/*
Q4. Prove the person -> FIR -> accused-occurrence grain for one accused.

Replace 119802 with the required accused_vid.
No names or other personal attributes are returned.
*/
WITH parameter AS (
    SELECT 119802::bigint AS accused_vid
),
root_rows AS (
    SELECT
        a.accused_vid,
        a.fir_reg_num,
        a.accused_srno,
        a.lang_cd,
        a.arr_surr_srno,
        a.accused_srno_migr,
        a.fir_accused_srno_migr,
        a.record_status,
        a.record_created_on,
        a.record_updated_on
    FROM fir.t_fir_accused_info AS a
    JOIN parameter AS p ON p.accused_vid = a.accused_vid
),
query_result AS (
    SELECT
        accused_vid,
        fir_reg_num,
        accused_srno,
        count(*) AS physical_rows,
        count(DISTINCT lang_cd) AS language_versions,
        array_agg(DISTINCT lang_cd ORDER BY lang_cd) AS lang_codes,
        count(DISTINCT arr_surr_srno) FILTER (WHERE arr_surr_srno IS NOT NULL) AS arrest_serial_count,
        array_agg(DISTINCT record_status ORDER BY record_status) AS record_statuses,
        min(record_created_on) AS first_row_created_on,
        max(record_updated_on) AS last_row_updated_on
    FROM root_rows
    GROUP BY accused_vid, fir_reg_num, accused_srno
    ORDER BY fir_reg_num, accused_srno
)
SELECT to_jsonb(query_result) AS result
FROM query_result;


/* Q4B. Show ambiguity if one person has multiple accused serials in one FIR. */
WITH parameter AS (
    SELECT 119802::bigint AS accused_vid
),
query_result AS (
    SELECT
        a.accused_vid,
        a.fir_reg_num,
        count(DISTINCT a.accused_srno) AS accused_serial_count,
        array_agg(DISTINCT a.accused_srno ORDER BY a.accused_srno) AS accused_serials
    FROM fir.t_fir_accused_info AS a
    JOIN parameter AS p ON p.accused_vid = a.accused_vid
    GROUP BY a.accused_vid, a.fir_reg_num
    HAVING count(DISTINCT a.accused_srno) > 1
    ORDER BY a.fir_reg_num
)
SELECT to_jsonb(query_result) AS result
FROM query_result;


/* Q4C. Show ambiguity if an accused_srno maps to multiple accused_vid values. */
WITH parameter AS (
    SELECT 119802::bigint AS accused_vid
),
target_serials AS (
    SELECT DISTINCT a.accused_srno
    FROM fir.t_fir_accused_info AS a
    JOIN parameter AS p ON p.accused_vid = a.accused_vid
),
query_result AS (
    SELECT
        a.accused_srno,
        count(DISTINCT a.accused_vid) AS accused_vid_count,
        array_agg(DISTINCT a.accused_vid ORDER BY a.accused_vid) AS accused_vids,
        count(DISTINCT a.fir_reg_num) AS fir_count
    FROM fir.t_fir_accused_info AS a
    JOIN target_serials AS s ON s.accused_srno = a.accused_srno
    GROUP BY a.accused_srno
    HAVING count(DISTINCT a.accused_vid) > 1
    ORDER BY a.accused_srno
)
SELECT to_jsonb(query_result) AS result
FROM query_result;


