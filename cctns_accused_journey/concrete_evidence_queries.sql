/*
Q2. Explode declared PK, UK, and FK constraints down to individual columns.

Evidence provided
  - Which PK/FK labels in the Mermaid diagram are database-enforced
  - Exact composite-key order, including whether lang_cd participates
  - Exact child-column -> parent-column mapping for every declared FK
*/
WITH target_relations AS (
    SELECT cls.oid
    FROM pg_class AS cls
    JOIN pg_namespace AS ns ON ns.oid = cls.relnamespace
    WHERE (ns.nspname, cls.relname) IN (
        ('fir',         't_fir_accused_info'),
        ('arrest',      't_arrest_memo'),
        ('interro',     't_interrogation_info'),
        ('court',       't_accused_remand'),
        ('court',       't_accused_remand_files'),
        ('bail',        't_accused_bail_details'),
        ('bail',        't_acc_bail_cancel_review'),
        ('finalreport', 't_accused_chargesheet'),
        ('court',       't_charges_framed_acts'),
        ('disposal',    't_accused_disposal'),
        ('disposal',    't_accused_disposal_acts'),
        ('disposal',    't_accused_punishment'),
        ('disposal',    't_accused_jail_details'),
        ('appeal',      't_accused_appeal'),
        ('appeal',      't_accused_appeal_acts')
    )
),
query_result AS (
SELECT
    child_ns.nspname AS child_schema,
    child.relname AS child_table,
    con.conname AS constraint_name,
    CASE con.contype
        WHEN 'p' THEN 'PRIMARY KEY'
        WHEN 'u' THEN 'UNIQUE'
        WHEN 'f' THEN 'FOREIGN KEY'
    END AS constraint_type,
    child_key.position AS column_position,
    child_col.attname AS child_column,
    parent_ns.nspname AS parent_schema,
    parent.relname AS parent_table,
    parent_col.attname AS parent_column,
    pg_get_constraintdef(con.oid, true) AS complete_definition
FROM pg_constraint AS con
JOIN pg_class AS child ON child.oid = con.conrelid
JOIN pg_namespace AS child_ns ON child_ns.oid = child.relnamespace
JOIN LATERAL unnest(con.conkey) WITH ORDINALITY
     AS child_key(attnum, position) ON true
JOIN pg_attribute AS child_col
  ON child_col.attrelid = con.conrelid
 AND child_col.attnum = child_key.attnum
LEFT JOIN pg_class AS parent ON parent.oid = con.confrelid
LEFT JOIN pg_namespace AS parent_ns ON parent_ns.oid = parent.relnamespace
LEFT JOIN LATERAL unnest(con.confkey) WITH ORDINALITY
     AS parent_key(attnum, position)
  ON con.contype = 'f'
 AND parent_key.position = child_key.position
LEFT JOIN pg_attribute AS parent_col
  ON parent_col.attrelid = con.confrelid
 AND parent_col.attnum = parent_key.attnum
WHERE con.contype IN ('p', 'u', 'f')
  AND (
      con.conrelid IN (SELECT oid FROM target_relations)
      OR con.confrelid IN (SELECT oid FROM target_relations)
  )
ORDER BY child_schema, child_table, constraint_type,
         constraint_name, column_position
)
SELECT to_jsonb(query_result) AS result
FROM query_result;


/*
Q3. Find unique indexes that may enforce a key even when no UK constraint exists.

Evidence provided
  - Candidate keys implemented as unique indexes
  - Partial/conditional uniqueness that information_schema constraints may miss
*/
SELECT to_jsonb(query_result) AS result
FROM (
SELECT
    ns.nspname AS table_schema,
    tbl.relname AS table_name,
    idx.relname AS index_name,
    ind.indisprimary AS is_primary,
    ind.indisunique AS is_unique,
    ind.indisvalid AS is_valid,
    pg_get_indexdef(ind.indexrelid) AS index_definition,
    pg_get_expr(ind.indpred, ind.indrelid) AS partial_predicate
FROM pg_index AS ind
JOIN pg_class AS tbl ON tbl.oid = ind.indrelid
JOIN pg_namespace AS ns ON ns.oid = tbl.relnamespace
JOIN pg_class AS idx ON idx.oid = ind.indexrelid
WHERE ind.indisunique
  AND (ns.nspname, tbl.relname) IN (
        ('fir',         't_fir_accused_info'),
        ('arrest',      't_arrest_memo'),
        ('interro',     't_interrogation_info'),
        ('court',       't_accused_remand'),
        ('court',       't_accused_remand_files'),
        ('bail',        't_accused_bail_details'),
