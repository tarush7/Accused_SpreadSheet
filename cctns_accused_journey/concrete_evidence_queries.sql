/*
Q6. Profile repeatable event keys for the chosen accused.

Interpretation
  - business_key_count > 1 means the module is repeatable for this person.
  - max_rows_per_key > 1 may be legitimate language versions or detail copies;
    use Q2/Q3 and lang_codes to decide whether it is a duplicate.
*/
WITH parameter AS (
    SELECT 119802::bigint AS accused_vid
),
events(table_name, business_key, lang_cd) AS (
    SELECT 'arrest.t_arrest_memo', arr_surr_srno::text, lang_cd::text
    FROM arrest.t_arrest_memo AS t JOIN parameter AS p USING (accused_vid)
    UNION ALL
    SELECT 'interro.t_interrogation_info', interro_srno::text, lang_cd::text
    FROM interro.t_interrogation_info AS t JOIN parameter AS p USING (accused_vid)
    UNION ALL
    SELECT 'court.t_accused_remand', remand_srno::text, lang_cd::text
    FROM court.t_accused_remand AS t JOIN parameter AS p USING (accused_vid)
    UNION ALL
    SELECT 'bail.t_accused_bail_details', bailer_srno::text, lang_cd::text
    FROM bail.t_accused_bail_details AS t JOIN parameter AS p USING (accused_vid)
    UNION ALL
    SELECT 'disposal.t_accused_disposal', accused_disposal_srno::text, lang_cd::text
    FROM disposal.t_accused_disposal AS t JOIN parameter AS p USING (accused_vid)
    UNION ALL
    SELECT 'appeal.t_accused_appeal', accused_appeal_srno::text, lang_cd::text
    FROM appeal.t_accused_appeal AS t JOIN parameter AS p USING (accused_vid)
),
per_key AS (
    SELECT
        table_name,
        business_key,
        count(*) AS rows_for_key,
        array_agg(DISTINCT lang_cd ORDER BY lang_cd) AS lang_codes
    FROM events
    WHERE business_key IS NOT NULL
    GROUP BY table_name, business_key
),
query_result AS (
SELECT
    table_name,
    count(*) AS business_key_count,
    sum(rows_for_key) AS physical_row_count,
    max(rows_for_key) AS max_rows_per_key,
    count(*) FILTER (WHERE rows_for_key > 1) AS keys_with_multiple_rows,
    jsonb_agg(
        jsonb_build_object(
            'business_key', business_key,
            'rows', rows_for_key,
            'lang_codes', lang_codes
        ) ORDER BY business_key
    ) FILTER (WHERE rows_for_key > 1) AS repeated_key_details
FROM per_key
GROUP BY table_name
ORDER BY table_name
)
SELECT to_jsonb(query_result) AS result
FROM query_result;


/*
Q6B. Compare arrest references and copied arrest dates without declaring a winner.

Rows returned here show the root FIR value beside every matching arrest memo.
The result will tell us whether accused_srno or fir_accused_srno is the usable
case-level join and whether arrest dates agree across modules.
*/
WITH parameter AS (
    SELECT 119802::bigint AS accused_vid
),
query_result AS (
SELECT
    f.accused_vid,
    f.fir_reg_num,
    f.accused_srno AS fir_accused_srno_value,
    f.arr_surr_srno AS fir_arr_surr_srno,
    f.arrest_surr_dt AS fir_arrest_date,
    a.accused_srno AS arrest_accused_srno,
    a.fir_accused_srno AS arrest_fir_accused_srno,
    a.arr_surr_srno AS arrest_arr_surr_srno,
    a.arrest_surrender_dt AS arrest_memo_date,
    (f.accused_srno = a.accused_srno) AS accused_srno_matches,
    (f.accused_srno = a.fir_accused_srno) AS fir_accused_srno_matches,
    (f.arr_surr_srno = a.arr_surr_srno) AS arr_surr_srno_matches,
    (f.arrest_surr_dt::text = a.arrest_surrender_dt::text) AS date_text_matches
FROM fir.t_fir_accused_info AS f
JOIN parameter AS p ON p.accused_vid = f.accused_vid
LEFT JOIN arrest.t_arrest_memo AS a
  ON a.accused_vid = f.accused_vid
 AND a.fir_reg_num = f.fir_reg_num
 AND (
      a.accused_srno = f.accused_srno
      OR a.fir_accused_srno = f.accused_srno
      OR a.arr_surr_srno = f.arr_surr_srno
 )
ORDER BY f.fir_reg_num, f.accused_srno, a.arr_surr_srno
)
SELECT to_jsonb(query_result) AS result
FROM query_result;


/*
Q7. Return the exact master rows for the important lookup families.

This JSON-safe search does not assume the master table's category/key column
names. It finds rows containing one of the known lookup-family labels and shows
the complete master row so the actual code and display-value columns are visible.
*/
SELECT to_jsonb(m) AS result
FROM mdm.m_lookup_masters AS m
WHERE EXISTS (
    SELECT 1
    FROM jsonb_each_text(to_jsonb(m)) AS attribute(column_name, column_value)
    WHERE upper(attribute.column_value) IN (
        'OFFCL_LANG',
        'ARR_SURR_TYPE',
        'ACC_DISPSL_TTP',
        'APPEAL_RSLT_TYP'
    )
)
ORDER BY to_jsonb(m)::text;


/*
Q7B. Profile actual status/result values for the selected accused.

This identifies nulls, sentinels, and code combinations needing a lookup or
business-rule explanation without exposing personal attributes.
*/
WITH parameter AS (
    SELECT 119802::bigint AS accused_vid
),
values_seen(table_name, field_name, field_value) AS (
    SELECT 'fir.t_fir_accused_info', 'accused_status_cd', accused_status_cd::text
    FROM fir.t_fir_accused_info AS t JOIN parameter AS p USING (accused_vid)
    UNION ALL
    SELECT 'fir.t_fir_accused_info', 'record_status', record_status::text
    FROM fir.t_fir_accused_info AS t JOIN parameter AS p USING (accused_vid)
    UNION ALL
    SELECT 'arrest.t_arrest_memo', 'arrest_type_cd', arrest_type_cd::text
    FROM arrest.t_arrest_memo AS t JOIN parameter AS p USING (accused_vid)
    UNION ALL
    SELECT 'arrest.t_arrest_memo', 'is_re_arrested', is_re_arrested::text
    FROM arrest.t_arrest_memo AS t JOIN parameter AS p USING (accused_vid)
    UNION ALL
    SELECT 'court.t_accused_remand', 'remand_status', remand_status::text
    FROM court.t_accused_remand AS t JOIN parameter AS p USING (accused_vid)
    UNION ALL
    SELECT 'bail.t_accused_bail_details', 'bail_status', bail_status::text
    FROM bail.t_accused_bail_details AS t JOIN parameter AS p USING (accused_vid)
    UNION ALL
    SELECT 'bail.t_accused_bail_details', 'is_bail_cancelled', is_bail_cancelled::text
    FROM bail.t_accused_bail_details AS t JOIN parameter AS p USING (accused_vid)
    UNION ALL
    SELECT 'disposal.t_accused_disposal', 'disposal_type_cd', disposal_type_cd::text
    FROM disposal.t_accused_disposal AS t JOIN parameter AS p USING (accused_vid)
    UNION ALL
    SELECT 'disposal.t_accused_disposal', 'is_appeal_preferred', is_appeal_preferred::text
    FROM disposal.t_accused_disposal AS t JOIN parameter AS p USING (accused_vid)
    UNION ALL
    SELECT 'appeal.t_accused_appeal', 'appeal_result_cd', appeal_result_cd::text
    FROM appeal.t_accused_appeal AS t JOIN parameter AS p USING (accused_vid)
    UNION ALL
    SELECT 'appeal.t_accused_appeal', 'is_punishment_retained', is_punishment_retained::text
