Purpose
  Resolve the remaining assumptions in the Mermaid diagram and module-wise report:
  actual PK/FK/UK definitions, key grain, repeated-event behavior, lookup meanings,
  indirect children, and authoritative chronology fields.

Safety
  - SELECT/CTE statements only; this file does not create, update, or delete data.
  - Replace 119802 with one accused_vid that has a reasonably complete journey.
  - Query 5 deliberately returns only allow-listed identifiers, statuses, and dates;
    it excludes names, addresses, phone numbers, documents, and narrative text.

