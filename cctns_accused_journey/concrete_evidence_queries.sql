/*
Q8. Check the three known indirect-child links for orphans.

Zero orphan rows supports the logical parent-child interpretation. A non-zero
result means the join is incomplete, legacy data is inconsistent, or another
column such as lang_cd must participate.
*/
SELECT to_jsonb(query_result) AS result
FROM (
SELECT
    'court.t_accused_remand_files -> court.t_accused_remand' AS relationship,
    count(*) FILTER (WHERE child.remand_srno IS NULL) AS null_child_keys,
    count(*) FILTER (
        WHERE child.remand_srno IS NOT NULL
          AND NOT EXISTS (
              SELECT 1
              FROM court.t_accused_remand AS parent
              WHERE parent.remand_srno = child.remand_srno
          )
    ) AS unmatched_nonnull_keys
FROM court.t_accused_remand_files AS child

UNION ALL

SELECT
    'bail.t_acc_bail_cancel_review -> bail.t_accused_bail_details',
    count(*) FILTER (WHERE child.bailer_srno IS NULL),
    count(*) FILTER (
        WHERE child.bailer_srno IS NOT NULL
          AND NOT EXISTS (
              SELECT 1
              FROM bail.t_accused_bail_details AS parent
              WHERE parent.bailer_srno = child.bailer_srno
          )
    )
FROM bail.t_acc_bail_cancel_review AS child

UNION ALL

SELECT
    'appeal.t_accused_appeal_acts -> appeal.t_accused_appeal',
    count(*) FILTER (WHERE child.accused_appeal_srno IS NULL),
    count(*) FILTER (
        WHERE child.accused_appeal_srno IS NOT NULL
          AND NOT EXISTS (
              SELECT 1
              FROM appeal.t_accused_appeal AS parent
              WHERE parent.accused_appeal_srno = child.accused_appeal_srno
          )
    )
FROM appeal.t_accused_appeal_acts AS child
ORDER BY relationship
) AS query_result;


/*
Q8B. Measure parent-child cardinality for the same indirect links.

This tells us whether each parent has zero, one, or many detail rows.
